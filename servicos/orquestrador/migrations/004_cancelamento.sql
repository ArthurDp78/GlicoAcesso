ALTER TABLE saga_execucoes DROP CONSTRAINT saga_execucoes_estado_check;
ALTER TABLE saga_execucoes ADD CHECK (estado IN (
    'AGUARDANDO_CONFIRMACAO', 'EM_EXECUCAO', 'COMPENSANDO', 'COMPENSACAO_PENDENTE',
    'CANCELANDO', 'CANCELAMENTO_PENDENTE', 'INTERROMPIDA', 'CONCLUIDA', 'COMPENSADA', 'CANCELADA'
));

CREATE UNIQUE INDEX saga_cancelamento_pendente_por_reserva ON saga_execucoes (reserva_id)
    WHERE tipo = 'CANCELAMENTO' AND estado IN ('AGUARDANDO_CONFIRMACAO', 'CANCELANDO', 'CANCELAMENTO_PENDENTE');
